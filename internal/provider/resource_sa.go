package provider

import (
	"context"
	"fmt"
	"strings"

	"github.com/hashicorp/terraform-plugin-framework/attr"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/types"
	"github.com/vladkanatov/terraform-provider-orchard/internal/client"
)

type ServiceAccountResource struct {
	client *client.Client
}

func NewServiceAccountResource() resource.Resource {
	return &ServiceAccountResource{}
}

type serviceAccountModel struct {
	Name  types.String `tfsdk:"name"`
	Token types.String `tfsdk:"token"`
	Roles types.List   `tfsdk:"roles"`
}

func serviceAccountModelFromSA(sa *client.ServiceAccount) serviceAccountModel {
	rolesVals := make([]attr.Value, len(sa.Roles))
	for i, r := range sa.Roles {
		rolesVals[i] = types.StringValue(r)
	}
	return serviceAccountModel{
		Name:  types.StringValue(sa.Name),
		Token: types.StringValue(sa.Token),
		Roles: types.ListValueMust(types.StringType, rolesVals),
	}
}

func stringSliceFromList(list types.List) []string {
	if list.IsNull() {
		return nil
	}
	var vals []string
	list.ElementsAs(context.Background(), &vals, false)
	return vals
}

func (r *ServiceAccountResource) Metadata(ctx context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_service_account"
}

func (r *ServiceAccountResource) Schema(ctx context.Context, req resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "Manages a service account in Orchard.",
		Attributes: map[string]schema.Attribute{
			"name": schema.StringAttribute{
				Required:    true,
				Description: "Unique name of the service account.",
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.RequiresReplace(),
				},
			},
			"token": schema.StringAttribute{
				Computed:    true,
				Sensitive:   true,
				Description: "Secret token used to access the API. Will be generated by the controller.",
			},
			"roles": schema.ListAttribute{
				ElementType: types.StringType,
				Optional:    true,
				Computed:    true, // Добавьте эту строку
				Description: "List of roles assigned to the service account.",
			},
		},
	}
}

func (r *ServiceAccountResource) Configure(ctx context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	cl, ok := req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Provider Data Type",
			fmt.Sprintf("Expected *client.Client, got %T", req.ProviderData),
		)
		return
	}
	r.client = cl
}

func (r *ServiceAccountResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan serviceAccountModel
	diags := req.Plan.Get(ctx, &plan)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	sa := &client.ServiceAccount{
		Name:  plan.Name.ValueString(),
		Roles: stringSliceFromList(plan.Roles),
	}

	created, err := r.client.CreateServiceAccount(ctx, sa)
	if err != nil {
		resp.Diagnostics.AddError("Failed to create service account", err.Error())
		return
	}

	state := serviceAccountModelFromSA(created)
	diags = resp.State.Set(ctx, state)
	resp.Diagnostics.Append(diags...)
}

func (r *ServiceAccountResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state serviceAccountModel
	diags := req.State.Get(ctx, &state)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	sa, err := r.client.GetServiceAccount(ctx, state.Name.ValueString())
	if err != nil {
		if strings.Contains(err.Error(), "404") {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Failed to read service account", err.Error())
		return
	}

	newState := serviceAccountModelFromSA(sa)
	// Сохраняем старый токен, если он был (так как токен не возвращается при GET)
	if !state.Token.IsNull() {
		newState.Token = state.Token
	}
	diags = resp.State.Set(ctx, newState)
	resp.Diagnostics.Append(diags...)
}

func (r *ServiceAccountResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan serviceAccountModel
	var state serviceAccountModel
	diags := req.Plan.Get(ctx, &plan)
	resp.Diagnostics.Append(diags...)
	diags = req.State.Get(ctx, &state)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	sa := &client.ServiceAccount{
		Name:  plan.Name.ValueString(),
		Roles: stringSliceFromList(plan.Roles),
	}

	updated, err := r.client.UpdateServiceAccount(ctx, state.Name.ValueString(), sa)
	if err != nil {
		resp.Diagnostics.AddError("Failed to update service account", err.Error())
		return
	}

	newState := serviceAccountModelFromSA(updated)
	// Сохраняем токен из старого состояния, если он был
	if !state.Token.IsNull() {
		newState.Token = state.Token
	}
	diags = resp.State.Set(ctx, newState)
	resp.Diagnostics.Append(diags...)
}

func (r *ServiceAccountResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state serviceAccountModel
	diags := req.State.Get(ctx, &state)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	err := r.client.DeleteServiceAccount(ctx, state.Name.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Failed to delete service account", err.Error())
		return
	}
}
